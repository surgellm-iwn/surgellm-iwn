"""CSV / JSON / LaTeX emission helpers.

Every number the paper reports should land in a CSV under ``results/tables/``
and in a LaTeX fragment under ``results/tables/latex/``, so a table in the
manuscript can be regenerated without hand-copying.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path
from typing import Dict, Iterable, List, Optional, Sequence

__all__ = ["write_csv", "write_json", "read_json", "to_latex_table",
           "fmt_mean_sd", "ensure_dir"]


def ensure_dir(path: str | Path) -> Path:
    p = Path(path)
    p.mkdir(parents=True, exist_ok=True)
    return p


def write_csv(rows: Sequence[Dict], path: str | Path,
              columns: Optional[Sequence[str]] = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = list(rows)
    if not rows:
        path.write_text("", encoding="utf-8")
        return path
    if columns is None:
        seen: List[str] = []
        for r in rows:
            for k in r:
                if k not in seen:
                    seen.append(k)
        columns = seen
    with path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(columns), extrasaction="ignore")
        w.writeheader()
        w.writerows(rows)
    return path


def write_json(payload, path: str | Path, indent: int = 2) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=indent, default=float), encoding="utf-8")
    return path


def read_json(path: str | Path):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def fmt_mean_sd(mean: float, sd: float, digits: int = 3, sd_digits: int = 3) -> str:
    """``0.940 ± .009`` in the paper's style."""
    sd_str = f"{sd:.{sd_digits}f}".lstrip("0")
    return f"{mean:.{digits}f} $\\pm$ {sd_str}"


def to_latex_table(rows: Sequence[Dict], columns: Sequence[str], caption: str,
                   label: str, path: str | Path,
                   column_format: Optional[str] = None,
                   headers: Optional[Sequence[str]] = None,
                   bold_max_columns: Sequence[str] = ()) -> Path:
    """Emit a booktabs table fragment."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = list(columns)
    heads = list(headers) if headers else [c.replace("_", " ") for c in cols]
    fmt = column_format or ("l" + "r" * (len(cols) - 1))

    best: Dict[str, float] = {}
    for c in bold_max_columns:
        vals = []
        for r in rows:
            try:
                vals.append(float(r.get(c)))
            except (TypeError, ValueError):
                pass
        if vals:
            best[c] = max(vals)

    lines = [
        "% auto-generated by surgellm.utils.io.to_latex_table -- do not edit",
        "\\begin{table}[t]", "\\centering", "\\small",
        f"\\begin{{tabular}}{{{fmt}}}", "\\toprule",
        " & ".join(f"\\textbf{{{h}}}" for h in heads) + " \\\\", "\\midrule",
    ]
    for r in rows:
        cells = []
        for c in cols:
            v = r.get(c, "")
            if isinstance(v, float):
                txt = f"{v:.3f}"
            else:
                txt = str(v)
            if c in best:
                try:
                    if abs(float(v) - best[c]) < 1e-12:
                        txt = f"\\textbf{{{txt}}}"
                except (TypeError, ValueError):
                    pass
            cells.append(txt.replace("_", "\\_"))
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}",
              f"\\caption{{{caption}}}", f"\\label{{{label}}}", "\\end{table}", ""]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path
